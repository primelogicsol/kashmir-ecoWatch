/** Maps DrinkingWaterSource → WaterEntity so WaterEntityListingPage & detail components can render it. */
export function toDrinkingWaterEntity(s: DrinkingWaterSource): WaterEntity {
  const qualityMap: Record<string, string> = {
    safe: 'excellent',
    'at-risk': 'moderate',
    contaminated: 'critical',
    unknown: 'data-deficient',
  };
  return {
    id: s.id,
    slug: s.slug,
    name: s.name,
    type: 'drinking-water',
    category: s.type.replace(/-/g, ' ').replace(/\b\w/g, c => c.toUpperCase()),
    description: s.description,
    district: s.district,
    elevation: 0,
    coordinates: s.coordinates,
    verificationStatus: 'verified',
    createdAt: s.lastUpdated,
    updatedAt: s.lastUpdated,
    waterQuality: {
      pH: 7.2,
      dissolvedOxygen: 8,
      turbidity: s.waterQualityStatus === 'safe' ? 1.5 : (s.waterQualityStatus === 'at-risk' ? 8.5 : 25),
      status: qualityMap[s.waterQualityStatus] || 'data-deficient',
    } as any,
    conservationStatus: s.status,
    threats: s.challenges,
  } as unknown as WaterEntity;
}

