  habitat: string; // 7. Ecological biome / habitat type
  elevation: string; // 8. Elevation in meters ASL (where documented)
  recordingDateTime: string; // 9. Recording date & local time
  season: string; // 10. Ecological season
  duration: string; // 11. Track duration (mm:ss) or pending notice
  recordingEquipment: string; // 12. Recorder, microphone, hydrophone, or filter notes
  recorderCredit: string; // 13. Field recordist attribution
  sourceRepository: string; // 14. Open scientific source repository
  originalRecordingId: string; // 15. Repository voucher ID (e.g., XC417770)
  license: string; // 16. Open license (CC0, CC BY 4.0, CC BY-SA 4.0, Public Domain)
