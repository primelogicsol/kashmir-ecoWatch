export function getInitialLandslideSnapshot(): {
  records: LandslideRecord[];
  roadCorridors: RoadCorridor[];
  officialBulletins: OfficialBulletin[];
  summary: {
    totalMonitoredZones: number;
    activeCorridorsCount: number;
    officialWarningsCount: number;
    highSusceptibilityCount: number;
    criticalCorridorAlerts: number;
    lastTelemetrySync: string;
  };
} {
  const now = new Date();
  const timeStr = now.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' });

  const highSusceptibilityCount = landslideData.filter(d => d.risk_level === 'Very High' || d.risk_level === 'High').length;
  const officialWarningsCount = officialBulletinsData.filter(b => b.warningLevel === 'Warning' || b.warningLevel === 'Watch').length;
  const criticalCorridorAlerts = roadCorridorsData.filter(c => c.operationalStatus !== 'Officially Open' && c.operationalStatus !== 'Open - Normal Flow').length;

  return {
    records: landslideData,
    roadCorridors: roadCorridorsData,
    officialBulletins: officialBulletinsData,
    summary: {
      totalMonitoredZones: landslideData.length,
      activeCorridorsCount: roadCorridorsData.length,
      officialWarningsCount,
      highSusceptibilityCount,
      criticalCorridorAlerts,
      lastTelemetrySync: timeStr,
    },
  };
}
