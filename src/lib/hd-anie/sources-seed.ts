/**
 * Dynamically merges the 24 core monitoring domains with any new modules added
 * to KEW's authoritative `NAVIGATION_GROUPS` so the newsroom taxonomy expands
 * automatically without maintaining a competing scientific taxonomy.
 */
export function getDynamicMonitoringTaxonomy(): AnieMonitoringDomainSpec[] {
  const knownHrefs = new Set(BASE_MONITORING_DOMAINS.map((d) => d.kewModuleHref));
  const dynamicExtras: AnieMonitoringDomainSpec[] = [];

  for (const group of GLOBAL_NAV_ITEMS || []) {
    if (group.href === '/himalayan-dispatch') continue;
    const subItems = getGlobalDropdownItems(group.label) || [];
    for (const item of subItems) {
      if (
        !item.href ||
        item.href === '#' ||
        item.isHeader ||
        knownHrefs.has(item.href) ||
        item.href.startsWith('/admin')
      ) {
        continue;
      }
      knownHrefs.add(item.href);
      const slugId = item.href.replace(/^\//, '').replace(/\//g, '-') || 'kew-hub';
      const cleanName = item.name.replace(/^[^\p{L}\p{N}]+/gu, '').trim();
      const words = `${cleanName} ${item.desc || ''}`
        .toLowerCase()
        .split(/[^a-z0-9]+/)
        .filter((w) => w.length >= 4);
      if (words.length === 0) continue;
      dynamicExtras.push({
        id: `dyn-${slugId}`,
        label: cleanName || item.name,
        subjects: [item.desc || group.label],
        keywords: Array.from(new Set(words)).slice(0, 8),
        kewModuleLabel: `${group.label} · ${cleanName || item.name}`,
        kewModuleHref: item.href,
        leadDepartmentId: 'field-reports',
        reportingBeatCode: 'BEAT 05',
      });
    }
  }

  return [...BASE_MONITORING_DOMAINS, ...dynamicExtras];
}
